import {readFile,writeFile} from 'node:fs/promises';
import {stripTypeScriptTypes} from 'node:module';

const mode=process.argv[2]??'--check';
if(!['--check','--write'].includes(mode)||process.argv.length>3)throw Error('Use --check or --write only.');
const header='// Generated by scripts/build-reference.mjs from reference/source; do not edit this file directly.\n';
for(const name of ['fowlerRetrieval','fowlerRetrieval.test']){
  const source=(await readFile(new URL(`../reference/source/${name}.ts`,import.meta.url),'utf8')).replaceAll('\r\n','\n');
  const generated=header+stripTypeScriptTypes(source,{mode:'transform'})
    .replaceAll("'../boundaries.mjs'","'./boundaries.mjs'")
    .replaceAll("'../fowlerRetrieval.mjs'","'./fowlerRetrieval.mjs'");
  const target=new URL(`../reference/${name}.mjs`,import.meta.url);
  if(mode==='--write')await writeFile(target,generated);
  else if(await readFile(target,'utf8')!==generated)throw Error(`Generated ${name}.mjs differs from its source. Run npm run build:reference, review the diff and rerun tests.`);
}
console.log(mode==='--write'?'Generated reference files updated.':'Generated reference files match their TypeScript source.');
